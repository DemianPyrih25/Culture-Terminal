import { readdirSync } from "node:fs";
import vm from "node:vm";
import { describe, expect, it } from "vitest";
import * as generated from "../../packages/agent/src/prompts.generated";
import {
  constantName,
  escapeTemplate,
  normalizePrompt,
  PROMPTS_DIR,
  readGeneratedFile,
  readPromptSources,
  renderPromptsModule,
  sha256,
} from "./build-prompts";

/** Evaluates an escaped template-literal body the way the TypeScript compiler will. */
function evalTemplate(body: string): unknown {
  return vm.runInNewContext(`\`${body}\``);
}

describe("build-prompts", () => {
  it("keeps packages/agent/src/prompts.generated.ts in sync with prompts/*.md (run `pnpm prompts:build`)", () => {
    expect(readGeneratedFile()).toBe(renderPromptsModule(readPromptSources()));
  });

  it("exports one constant and one hash per Markdown prompt, and the hashes match the constants", () => {
    const files = readdirSync(PROMPTS_DIR).filter((f) => f.endsWith(".md"));
    expect(files).toEqual(expect.arrayContaining(["director.md", "clerk.md"]));
    const exported = generated as unknown as Record<string, unknown>;
    for (const source of readPromptSources()) {
      expect(exported[source.constant], source.constant).toBe(source.text);
      expect(generated.PROMPT_HASHES[source.name as keyof typeof generated.PROMPT_HASHES]).toBe(sha256(source.text));
    }
    expect(Object.keys(generated.PROMPT_HASHES).sort()).toEqual(files.map((f) => f.slice(0, -3)).sort());
  });

  it("normalises BOM, CRLF and trailing whitespace, so checkouts on any OS hash alike", () => {
    expect(normalizePrompt("\uFEFF# A\r\n\r\nline\rend  \r\n\n")).toBe("# A\n\nline\nend");
    expect(sha256(normalizePrompt("a\r\nb\r\n"))).toBe(sha256("a\nb"));
  });

  it("escapes template-literal syntax so the embedded text round-trips exactly", () => {
    const tricky = "tokens {{M12}} and [E4], a `code` span, a ${placeholder}, a \\ backslash, $ alone and \\` both";
    expect(evalTemplate(escapeTemplate(tricky))).toBe(tricky);
    expect(evalTemplate(escapeTemplate("line one\nline two"))).toBe("line one\nline two");
  });

  it("names constants after the file stem", () => {
    expect(constantName("director")).toBe("DIRECTOR_PROMPT");
    expect(constantName("ghost-v2")).toBe("GHOST_V2_PROMPT");
  });

  it("renders a header that marks the file as generated", () => {
    const out = renderPromptsModule([{ name: "x", constant: "X_PROMPT", text: "hi", sha256: sha256("hi") }]);
    expect(out.split("\n")[0]).toMatch(/^\/\/ Generated by tools\/dev\/build-prompts\.ts .*do not edit\.$/);
    expect(out).toContain("export const X_PROMPT = `hi`;");
    expect(out).toContain(`x: "${sha256("hi")}",`);
  });
});
