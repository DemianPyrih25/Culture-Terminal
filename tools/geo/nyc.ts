// Builds New York City's gazetteer modules (D28, P1 #5) from the NYC Department of City Planning's 2020
// Neighborhood Tabulation Areas, residential NTAs only, at one of two levels:
//   --level nta   the 197 tabulation areas                              -> packages/geo/src/data/nyc-ntas.ts
//   --level cdta  the 59 community districts they make up (their CDTAs) -> packages/geo/src/data/nyc-districts.ts
// ATTRIBUTION.md records the source, edition, licence, retrieval date and every transformation. Which
// level GAZETTEER_LOADERS serves depends on the geohash precision of Qloo's NYC heatmaps: packages/geo/src/gazetteer.ts.
//
// Usage: pnpm exec tsx tools/geo/nyc.ts --level nta|cdta --nta <ntas.geojson> --gnis <DomesticNames_NY.txt> [--interval <m>] [--out <file>] [--dry]
//
// Inputs, downloaded by hand to a local folder and never committed:
//   --nta   NYC Open Data dataset 9nt8-h7nd, "2020 Neighborhood Tabulation Areas (NTAs)", as GeoJSON:
//           https://data.cityofnewyork.us/resource/9nt8-h7nd.geojson?$limit=1000
//   --gnis  The USGS Geographic Names Information System's names for New York State (public domain):
//           Text/DomesticNames_NY.txt inside
//           https://prd-tnm.s3.amazonaws.com/StagedProducts/GeographicNames/DomesticNames/DomesticNames_NY_Text.zip
//
// Steps: keep the residential NTAs (NTAType 0). DCP flags the others as non-residential (NTAType 5-9:
// parks, cemeteries, airports, Rikers Island and special areas such as military posts), with few or no
// residents; they are left out, so a point inside one lies in no area, as a point outside the city does
// -> the shared build (tools/geo/build.ts), which at --level cdta dissolves the NTAs into the community
// district each one records -> approximate aliases (approximateAliases below) -> the module.
