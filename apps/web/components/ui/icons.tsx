/** A Lucide icon name of the set. */
export type IconName = keyof typeof ICON_PATHS;

/** Every icon name, in gallery order (controls, status and content, topic and category). */
export const ICON_NAMES = Object.keys(ICON_PATHS) as IconName[];

/** True when `value` names an icon of the set. */
export function isIconName(value: unknown): value is IconName {
  return typeof value === "string" && Object.hasOwn(ICON_PATHS, value);
}

export interface IconProps extends Omit<SVGProps<SVGSVGElement>, "children" | "direction" | "name"> {
  /** Rendered width and height in px (default 16). Sizes in use: 12, 14, 16, 18, 20, 28, 32. */
  size?: number;
  /** Accessible name. Without it the icon is aria-hidden. */
  title?: string;
}

function Svg({ size = 16, title, strokeWidth = 2, children, ...rest }: IconProps & { children: ReactNode }) {
  const labelled = title !== undefined && title !== "";
  return (
    <svg
      xmlns="http://www.w3.org/2000/svg"
      width={size}
      height={size}
      viewBox="0 0 24 24"
      fill="none"
      stroke="currentColor"
      strokeWidth={strokeWidth}
      strokeLinecap="round"
      strokeLinejoin="round"
      focusable="false"
      {...(labelled ? { role: "img", "aria-label": title } : { "aria-hidden": true })}
      {...rest}
    >
      {labelled ? <title>{title}</title> : null}
      {children}
    </svg>
  );
}

/** Any icon of the set by name. */
export function Icon({ name, ...props }: IconProps & { name: IconName }) {
  return (
    <Svg data-icon={name} {...props}>
      {ICON_PATHS[name]}
    </Svg>
  );
}

/** The loading spinner: loader-circle, turning only when the reader allows motion. */
export function Spinner({ className, ...props }: IconProps) {
  return <Icon name="loader-circle" className={cx("motion-safe:animate-spin", className)} {...props} />;
}
