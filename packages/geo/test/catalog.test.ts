// catalog.ts: every shipped area's names, centroid and area, generated from the data modules. This test
// writes it (`pnpm --filter @ct/geo test -u`) and fails while it is out of date.
import { MetroId } from "@ct/contracts";
import { describe, expect, it } from "vitest";
import { catalogEntry } from "../src/geo";
import { GAZETTEER_CATALOG, GAZETTEER_LOADERS, loadGazetteers, type Gazetteer, type GazetteerMetro } from "../src/index";

const GAZETTEERS = await loadGazetteers();

/** The catalog module's text: one line per area, metros in MetroId order. */
export function renderCatalog(gazetteers: Readonly<Partial<Record<GazetteerMetro, Gazetteer>>>): string {
  const lines = [
    "// Generated by packages/geo/test/catalog.test.ts from the gazetteer data modules (src/data): do not edit",
    "// by hand. After a gazetteer build, regenerate it with `pnpm --filter @ct/geo test -u`. Every shipped",
    "// area's id, names, centroid and area without its polygons, so names resolve and areas list without",
    "// loading a gazetteer; createGeo loads a metro's polygons on first use and checks them against this.",
    'import type { GazetteerCatalog } from "./gazetteer";',
    "",
    "export const GAZETTEER_CATALOG: GazetteerCatalog = {",
  ];
  for (const metro of MetroId.options) {
    const g = gazetteers[metro];
    if (g === undefined) continue;
    const entry = catalogEntry(g);
    lines.push(`  ${metro}: {`, `    source: ${JSON.stringify(entry.source)},`, "    areas: [");
    for (const a of entry.areas) lines.push(`      ${JSON.stringify(a)},`);
    lines.push("    ],", "  },");
  }
  lines.push("};", "");
  return lines.join("\n");
}

describe("catalog.ts", () => {
  it("is generated from the shipped gazetteers", async () => {
    await expect(renderCatalog(GAZETTEERS)).toMatchFileSnapshot("../src/catalog.ts");
  });

  it("lists exactly the metros a loader serves", () => {
    expect(Object.keys(GAZETTEER_CATALOG)).toEqual(Object.keys(GAZETTEER_LOADERS));
    expect(Object.keys(GAZETTEER_LOADERS)).toEqual(MetroId.options);
  });
});
